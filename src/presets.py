def p(raw=None, **kw):
    """raw: {slider: valor} (como están guardados en un proyecto); kw: alias de arriba; m1..m6 = (fuente, destino, %)."""
    out = dict(raw or {})
    for k, v in kw.items():
        if k[0] == "m" and k[1:].isdigit():
            b = 73 + 3 * (int(k[1:]) - 1)
            out[b], out[b + 1], out[b + 2] = v
        else:
            out[ALIAS[k]] = v
    return out


